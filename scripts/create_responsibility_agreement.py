def font(run, size=8.8, bold=False, color="111111"):
    run.font.name = "Arial"
    run._element.get_or_add_rPr().rFonts.set(qn("w:eastAsia"), "Arial")
    run.font.size = Pt(size)
    run.bold = bold
    run.font.color.rgb = RGBColor.from_string(color)


def para(doc, text="", size=8.8, bold=False, before=0, after=2.5, align=None):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(before)
    p.paragraph_format.space_after = Pt(after)
    p.paragraph_format.line_spacing = 1.0
    if align is not None:
        p.alignment = align
    font(p.add_run(text), size=size, bold=bold)
    return p


def add_clause(doc, number, title, text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(2)
    p.paragraph_format.space_after = Pt(2.5)
    p.paragraph_format.line_spacing = 1.0
    font(p.add_run(f"{number}. {title}: "), size=8.7, bold=True)
    font(p.add_run(text), size=8.7)


